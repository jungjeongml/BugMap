function png(value,width,height) {
  const bytes=Buffer.from(value,'base64');
  assert.equal(bytes.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
  assert.equal(bytes.readUInt32BE(16),width);
  assert.equal(bytes.readUInt32BE(20),height);
  return bytes;
}
function verifyPreservation(receipt,defaultId) {
  const {before,after}=receipt;
  assert.deepEqual(after.roots,before.roots,'Existing root list and geometry');
  const oldPoints=after.flowStartingPoints.filter(v=>before.roots.some(n=>n.id===v.nodeId));
  const autoPoints=after.flowStartingPoints.filter(v=>!before.roots.some(n=>n.id===v.nodeId));
  assert.deepEqual(oldPoints,before.flowStartingPoints,'Existing flow starting points');
  assert.ok(navigate(after.ctaReactions,defaultId));
  assert.deepEqual(after.ctaReactions.slice(0,-1),before.ctaReactions,'Existing CTA reactions');
  assert.equal(after.ctaReactions.length,before.ctaReactions.length+1);
  const summarise=(snapshot,normalize)=>snapshot.anchors.map(({id,tree,png:data})=>{
    const normalization=structuredClone(tree);
    if (id===targets.nodeId && normalize) {
      const cta=walk(normalization).find(n=>n.id===targets.recordButtonId);
      assert.ok(cta);
      cta.reactions=before.ctaReactions;
    }
    return {id,name:tree.name,nodeCount:walk(tree).length,treeSha256:sha(JSON.stringify(tree)),
      treeSha256IgnoringAddedCta:sha(JSON.stringify(normalization)),...(data?{captureSha256:sha(Buffer.from(data,'base64'))}:{})};
  });
  const beforeAnchors=summarise(before,false);
  const afterAnchors=summarise(after,true);
  assert.deepEqual(beforeAnchors.map(({treeSha256,...properties})=>properties),afterAnchors.map(({treeSha256,...properties})=>properties),
    'Native trees, existing prototype reactions, and PNGs match except the appended CTA route');
  return {method:'Native Figma snapshots immediately before and after the scoped write',checkedAt:new Date().toISOString(),
    fileKey:target.fileKey,pageId:target.pageId,ctaId:targets.recordButtonId,autoGeneratedFlowStartingPoints:autoPoints,
    before:{roots:before.roots,ctaReactions:before.ctaReactions,flowStartingPoints:before.flowStartingPoints,anchors:beforeAnchors},
    after:{roots:after.roots,ctaReactions:after.ctaReactions,flowStartingPoints:after.flowStartingPoints,anchors:afterAnchors}};
}
